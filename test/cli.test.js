import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { test } from "node:test";

const CLI_ENTRY = path.resolve("dist/cli.cjs");
const packageJson = JSON.parse(
  fs.readFileSync(path.resolve("package.json"), "utf8"),
);

// The CLI is the only shipped entry point that pulls in `commander`, so it is the
// one place the published `engines.node` floor is genuinely exercised. Launch the
// bundle as a real process: that also proves the `../package.json` import was
// inlined rather than emitted as an external require (which would break once the
// tarball, containing only `dist`, is installed). stdin is ignored so a stray
// prompt cannot hang the suite, and stdout/stderr are captured instead of being
// lost behind execFileSync's `[null, null, null]`.
//
// `input` answers the interactive prompts and `cwd` decides where a relative
// project name is created, so a `create` run can be driven from a temp directory
// without a package manager, a network, or a terminal.
function runCli(args, { input, cwd } = {}) {
  const command = {
    encoding: "utf8",
    stdio: [input === undefined ? "ignore" : "pipe", "pipe", "pipe"],
    ...(input === undefined ? {} : { input }),
    ...(cwd === undefined ? {} : { cwd }),
  };

  try {
    return {
      code: 0,
      stdout: execFileSync(process.execPath, [CLI_ENTRY, ...args], command),
      stderr: "",
    };
  } catch (error) {
    return {
      code: error.status ?? 1,
      stdout: error.stdout || "",
      stderr: error.stderr || "",
    };
  }
}

test("the CLI resolves commander and prints the inlined package version", () => {
  const { code, stdout, stderr } = runCli(["--version"]);
  assert.equal(code, 0, `--version exited with ${code}:\n${stderr}`);
  assert.equal(
    stdout.trim(),
    packageJson.version,
    `dist/cli.cjs reports ${JSON.stringify(stdout.trim())} but package.json is ` +
      `${packageJson.version}; rebuild with "pnpm run build"`,
  );
});

test("the CLI help is generated by commander", () => {
  const { code, stdout, stderr } = runCli(["--help"]);
  assert.equal(code, 0, `--help exited with ${code}:\n${stderr}`);
  assert.match(stdout, /Usage: next-vite-router \[options\] \[command\]/);
  assert.match(stdout, /-V, --version/);
  assert.match(stdout, /create\s+Create a new Vite project/);
  // `create` is the only command the CLI publishes: wiring an existing project up
  // is the documented manual setup, so the help table must not offer a second one.
  assert.doesNotMatch(stdout, /configure/);
});

test("the CLI reports an unknown command as a message and exits 1", () => {
  const { code, stderr } = runCli(["bogus"]);
  assert.equal(code, 1, "an unknown command should not exit successfully");
  assert.match(stderr, /unknown command 'bogus'/);
  // commander exits through its own error path, so no raw stack may leak.
  assert.doesNotMatch(stderr, /^\s+at\s/m);
});

// ---------------------------------------------------------------------------
// `create`: the two guards that run before any package manager is invoked.
//
// Everything after them needs a network, a package manager, and a TTY for the
// prompts, so these guards are the only `create` paths testable as a real
// process. They exist because create-vite prints "Operation cancelled" and still
// exits 0 on an existing directory, which used to let `create` carry on and wipe
// that folder's src/ content.
// ---------------------------------------------------------------------------

test("create rejects a project name that is not a safe directory name", () => {
  const cwd = fs.mkdtempSync(path.join(os.tmpdir(), "nvr-cli-name-"));
  try {
    const { code, stdout } = runCli(["create"], { cwd, input: "Bad Name!\n" });

    assert.equal(code, 1, `an invalid name should not exit successfully:\n${stdout}`);
    assert.match(stdout, /Invalid project name/);
    // Rejected before the filesystem was touched, so nothing was scaffolded.
    assert.deepEqual(fs.readdirSync(cwd), []);
  } finally {
    fs.rmSync(cwd, { recursive: true, force: true });
  }
});

test("create refuses an existing directory and leaves its files alone", () => {
  const cwd = fs.mkdtempSync(path.join(os.tmpdir(), "nvr-cli-exists-"));
  const appPath = path.join(cwd, "taken", "src", "App.tsx");
  try {
    fs.mkdirSync(path.dirname(appPath), { recursive: true });
    fs.writeFileSync(appPath, "// real work\n", "utf8");

    const { code, stdout } = runCli(["create"], { cwd, input: "taken\n" });

    assert.equal(code, 1, `an existing directory should not exit successfully:\n${stdout}`);
    assert.match(stdout, /Directory "taken" already exists\./);
    assert.equal(fs.readFileSync(appPath, "utf8"), "// real work\n");
  } finally {
    fs.rmSync(cwd, { recursive: true, force: true });
  }
});

// The two guards above answer the name prompt, which a pipe can carry. The menu
// after them is a different matter: a `select` never resolves once stdin is not a
// terminal, so a piped `create` used to end at Node's "unsettled top-level await" -
// exit code 13, and not one sentence about the menu it could not show.
test("create stops before the template menu when it has no terminal to answer it", () => {
  const cwd = fs.mkdtempSync(path.join(os.tmpdir(), "nvr-cli-tty-"));
  try {
    // A valid name that does not exist yet, so both pre-flight guards pass and the
    // run reaches the point a pipe cannot get past.
    const { code, stdout } = runCli(["create"], { cwd, input: "piped-app\n" });

    assert.equal(
      code,
      1,
      `a run with no terminal should say so instead of dying quietly:\n${stdout}`,
    );
    assert.match(stdout, /needs an interactive terminal/);
    // The fix it offers is a manual one now: no second command is named.
    assert.doesNotMatch(stdout, /configure/);
    // It stopped before any package manager ran, so nothing was created.
    assert.deepEqual(fs.readdirSync(cwd), []);
  } finally {
    fs.rmSync(cwd, { recursive: true, force: true });
  }
});
