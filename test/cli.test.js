import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { test } from "node:test";

const CLI_ENTRY = path.resolve("dist/cli.cjs");
const packageJson = JSON.parse(
  fs.readFileSync(path.resolve("package.json"), "utf8"),
);

// The CLI is the only shipped entry point that pulls in `commander`, so it is the
// one place the published `engines.node` floor is genuinely exercised. Launch the
// bundle as a real process: that also proves the `../package.json` import was
// inlined rather than emitted as an external require (which would break once the
// tarball, containing only `dist`, is installed). stdin is ignored so a stray
// prompt cannot hang the suite, and stdout/stderr are captured instead of being
// lost behind execFileSync's `[null, null, null]`.
//
// `input` answers the interactive prompts, `cwd` decides where a relative
// project name is created, and `env` can pin the package manager the detection
// reports - so a `create` run can be driven from a temp directory and a generated
// README can be asserted against one known manager instead of whichever the host
// happens to have.
function runCli(args, { input, cwd, env } = {}) {
  const command = {
    encoding: "utf8",
    stdio: [input === undefined ? "ignore" : "pipe", "pipe", "pipe"],
    ...(input === undefined ? {} : { input }),
    ...(cwd === undefined ? {} : { cwd }),
    ...(env === undefined ? {} : { env: { ...process.env, ...env } }),
  };

  try {
    return {
      code: 0,
      stdout: execFileSync(process.execPath, [CLI_ENTRY, ...args], command),
      stderr: "",
    };
  } catch (error) {
    return {
      code: error.status ?? 1,
      stdout: error.stdout || "",
      stderr: error.stderr || "",
    };
  }
}

test("the CLI resolves commander and prints the inlined package version", () => {
  const { code, stdout, stderr } = runCli(["--version"]);
  assert.equal(code, 0, `--version exited with ${code}:\n${stderr}`);
  assert.equal(
    stdout.trim(),
    packageJson.version,
    `dist/cli.cjs reports ${JSON.stringify(stdout.trim())} but package.json is ` +
      `${packageJson.version}; rebuild with "pnpm run build"`,
  );
});

test("the CLI help is generated by commander", () => {
  const { code, stdout, stderr } = runCli(["--help"]);
  assert.equal(code, 0, `--help exited with ${code}:\n${stderr}`);
  assert.match(stdout, /Usage: next-vite-router \[options\] \[command\]/);
  assert.match(stdout, /-V, --version/);
  assert.match(stdout, /create\s+Create a new Vite project/);
  assert.match(stdout, /configure \[options\]/);
  // Matched separately from the command name: commander wraps the help table, so
  // name and description do not have to share a line.
  assert.match(stdout, /Configure next-vite-router in an existing/);
});

test("the CLI reports an unknown command as a message and exits 1", () => {
  const { code, stderr } = runCli(["bogus"]);
  assert.equal(code, 1, "an unknown command should not exit successfully");
  assert.match(stderr, /unknown command 'bogus'/);
  // commander exits through its own error path, so no raw stack may leak.
  assert.doesNotMatch(stderr, /^\s+at\s/m);
});

// ---------------------------------------------------------------------------
// `create`: the two guards that run before any package manager is invoked.
//
// Everything after them needs a network, a package manager, and a TTY for the
// prompts, so these guards are the only `create` paths testable as a real
// process. They exist because create-vite prints "Operation cancelled" and still
// exits 0 on an existing directory, which used to let `create` carry on and wipe
// that folder's src/ content.
// ---------------------------------------------------------------------------

test("create rejects a project name that is not a safe directory name", () => {
  const cwd = fs.mkdtempSync(path.join(os.tmpdir(), "nvr-cli-name-"));
  try {
    const { code, stdout } = runCli(["create"], { cwd, input: "Bad Name!\n" });

    assert.equal(code, 1, `an invalid name should not exit successfully:\n${stdout}`);
    assert.match(stdout, /Invalid project name/);
    // Rejected before the filesystem was touched, so nothing was scaffolded.
    assert.deepEqual(fs.readdirSync(cwd), []);
  } finally {
    fs.rmSync(cwd, { recursive: true, force: true });
  }
});

test("create refuses an existing directory and leaves its files alone", () => {
  const cwd = fs.mkdtempSync(path.join(os.tmpdir(), "nvr-cli-exists-"));
  const appPath = path.join(cwd, "taken", "src", "App.tsx");
  try {
    fs.mkdirSync(path.dirname(appPath), { recursive: true });
    fs.writeFileSync(appPath, "// real work\n", "utf8");

    const { code, stdout } = runCli(["create"], { cwd, input: "taken\n" });

    assert.equal(code, 1, `an existing directory should not exit successfully:\n${stdout}`);
    assert.match(stdout, /Directory "taken" already exists\./);
    assert.equal(fs.readFileSync(appPath, "utf8"), "// real work\n");
  } finally {
    fs.rmSync(cwd, { recursive: true, force: true });
  }
});

// ---------------------------------------------------------------------------
// `configure`: the file-rewriting half of the CLI, reachable without create-vite,
// an install, or a TTY. The project below stands in for what
// `npm create vite --template react-ts` leaves behind.
// ---------------------------------------------------------------------------

const VITE_CONFIG = `import { defineConfig } from 'vite'
import react from '@vitejs/plugin-react'

export default defineConfig({
  plugins: [react()],
})
`;

const INDEX_HTML = `<!doctype html>
<html lang="en">
  <body>
    <div id="root"></div>
    <script type="module" src="/src/main.tsx"></script>
  </body>
</html>
`;

function makeViteProject(dir) {
  fs.mkdirSync(path.join(dir, "src", "assets"), { recursive: true });
  fs.writeFileSync(path.join(dir, "vite.config.ts"), VITE_CONFIG, "utf8");
  fs.writeFileSync(path.join(dir, "index.html"), INDEX_HTML, "utf8");
  fs.writeFileSync(
    path.join(dir, "tsconfig.app.json"),
    `${JSON.stringify({ compilerOptions: { paths: {} }, include: ["src"] }, null, 2)}\n`,
    "utf8",
  );
  fs.writeFileSync(path.join(dir, "src", "main.tsx"), "// the app's own entry\n", "utf8");
  fs.writeFileSync(path.join(dir, "src", "App.tsx"), "// the app's own component\n", "utf8");
  fs.writeFileSync(path.join(dir, "src", "assets", "react.svg"), "<svg/>\n", "utf8");
  return dir;
}

const read = (file) => fs.readFileSync(file, "utf8");
const pluginCalls = (content) => (content.match(/nextViteRouter\s*\(/g) ?? []).length;

test("configure refuses a directory that is not a Vite project", () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "nvr-cli-no-vite-"));
  try {
    const { code, stdout } = runCli(["configure", "--dir", dir]);

    assert.equal(code, 1, `a project without a Vite config should fail:\n${stdout}`);
    assert.match(stdout, /No Vite config found/);
    // Failed on the target alone: not one file was written.
    assert.deepEqual(fs.readdirSync(dir), []);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

test("configure will not replace an entry point it was not told to", () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "nvr-cli-entry-"));
  const project = makeViteProject(path.join(root, "project"));
  try {
    const { code, stdout } = runCli(["configure", "--dir", project]);

    assert.equal(code, 1, `an existing main.tsx needs --yes:\n${stdout}`);
    assert.match(stdout, /main\.tsx.* already exists and configure replaces it/s);
    // Refused up front, so the project is exactly as it was found.
    assert.equal(read(path.join(project, "src", "main.tsx")), "// the app's own entry\n");
    assert.equal(read(path.join(project, "vite.config.ts")), VITE_CONFIG);
    assert.equal(fs.existsSync(path.join(project, "src", "app")), false);
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
  }
});

test("configure wires an existing src/ project without deleting from it", () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "nvr-cli-src-"));
  const project = makeViteProject(path.join(root, "project"));
  try {
    const { code, stdout } = runCli(["configure", "--yes", "--dir", project]);
    assert.equal(code, 0, `configure exited with ${code}:\n${stdout}`);

    const viteConfig = read(path.join(project, "vite.config.ts"));
    assert.match(viteConfig, /import \{ nextViteRouter \} from "next-vite-router\/plugin";/);
    assert.match(viteConfig, /plugins: \[react\(\), nextViteRouter\(\)\]/);
    assert.match(viteConfig, /"@": resolve\(fileURLToPath\(new URL\("\.\/src", import\.meta\.url\)\)\)/);
    assert.equal(pluginCalls(viteConfig), 1);

    // Route tree, entry, styles, and the placeholder declaration.
    assert.match(read(path.join(project, "src", "app", "page.tsx")), /export default function Page/);
    assert.match(read(path.join(project, "src", "app", "layout.tsx")), /<Outlet \/>/);
    assert.match(read(path.join(project, "src", "app", "example", "page.tsx")), /ExamplePage/);
    assert.match(read(path.join(project, "src", "main.tsx")), /from 'next-vite-router\/routes'/);
    assert.match(read(path.join(project, "src", "globals.css")), /box-sizing: border-box/);
    assert.match(
      read(path.join(project, "src", "routes.d.ts")),
      /declare module 'next-vite-router\/routes'/,
    );

    // The generated declaration dirties the working tree on every build, so the
    // scaffold has to ignore it.
    assert.match(
      read(path.join(project, ".gitignore")),
      /^src\/routes\.d\.ts$/m,
    );

    // Alias and include for the src layout; the entry script keeps pointing at it.
    const tsConfig = JSON.parse(read(path.join(project, "tsconfig.app.json")));
    assert.deepEqual(tsConfig.compilerOptions.paths["@/*"], ["./src/*"]);
    assert.deepEqual(tsConfig.include, ["src"]);
    assert.match(read(path.join(project, "index.html")), /src="\/src\/main\.tsx"/);

    // Nothing of the app's own is removed: leftovers are reported instead.
    assert.match(read(path.join(project, "src", "App.tsx")), /the app's own component/);
    assert.match(stdout, /Nothing was deleted/);
    assert.match(stdout, /App\.tsx/);
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
  }
});

test("configure is idempotent", () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "nvr-cli-twice-"));
  const project = makeViteProject(path.join(root, "project"));
  try {
    runCli(["configure", "--yes", "--dir", project]);
    const first = read(path.join(project, "vite.config.ts"));

    const { code, stdout } = runCli(["configure", "--yes", "--dir", project]);
    assert.equal(code, 0, `the second run exited with ${code}:\n${stdout}`);

    // A second run must not stack a second plugin call, and must not rewrite the
    // file at all when there is nothing left to add.
    assert.equal(read(path.join(project, "vite.config.ts")), first);
    assert.equal(pluginCalls(first), 1);
    assert.match(stdout, /already called nextViteRouter/);
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
  }
});

test("configure --no-src moves the generated structure to the project root", () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "nvr-cli-no-src-"));
  const project = makeViteProject(path.join(root, "project"));
  try {
    // No root-level main.tsx exists, so the entry check does not need --yes.
    const { code, stdout } = runCli(["configure", "--no-src", "--dir", project]);
    assert.equal(code, 0, `configure exited with ${code}:\n${stdout}`);

    const viteConfig = read(path.join(project, "vite.config.ts"));
    assert.equal(pluginCalls(viteConfig), 1);
    assert.match(viteConfig, /nextViteRouter\(\{ pagesDir: "app" \}\)/);

    assert.match(read(path.join(project, "app", "page.tsx")), /export default function Page/);
    assert.match(read(path.join(project, "main.tsx")), /from 'next-vite-router\/routes'/);
    assert.match(read(path.join(project, "globals.css")), /box-sizing: border-box/);

    // The template entry script has to stop pointing into src/, and the
    // declaration is generated at the root now, so that is what gets ignored.
    assert.match(read(path.join(project, "index.html")), /src="\/main\.tsx"/);
    assert.match(
      read(path.join(project, ".gitignore")),
      /^routes\.d\.ts$/m,
    );
    assert.equal(fs.existsSync(path.join(project, "src", "app")), false);
    // src/ itself survives: a project may still import from it.
    assert.match(read(path.join(project, "src", "App.tsx")), /the app's own component/);

    // The generated README describes the layout it just wrote, and names the
    // declaration where this layout puts it - at the root, not under src/.
    const readme = read(path.join(project, "README.md"));
    assert.match(readme, /Pages live in `app\/`\./);
    assert.match(readme, /`routes\.d\.ts` is rewritten/);
    assert.doesNotMatch(readme, /src\/app/);
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
  }
});

// ---------------------------------------------------------------------------
// What the scaffold hands the project: a README a stranger can run the app from,
// a starter that reads correctly on a dark theme, and the promise that none of it
// replaces a document or a page the project already wrote.
// ---------------------------------------------------------------------------

test("configure writes a README the project can be run from", () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "nvr-cli-readme-"));
  const project = makeViteProject(path.join(root, "project"));
  try {
    // Pin the manager to npm whatever ran the suite, because the README is
    // supposed to name the detected one in that manager's own spelling.
    const { code, stdout } = runCli(["configure", "--yes", "--dir", project], {
      env: { PREFERRED_PM: "npm", npm_config_user_agent: "" },
    });
    assert.equal(code, 0, `configure exited with ${code}:\n${stdout}`);

    const readme = read(path.join(project, "README.md"));
    assert.match(readme, /`npm run dev`/);
    assert.match(readme, /`npm run build`/);
    assert.match(readme, /`npm run preview`/);

    for (const convention of [
      "page.tsx",
      "layout.tsx",
      "loading.tsx",
      "error.tsx",
      "not-found.tsx",
      "[id]",
      "[...slug]",
      "(marketing)",
    ]) {
      assert.ok(
        readme.includes(convention),
        `the conventions table never mentions ${convention}`,
      );
    }

    // The declaration is documented as what it is: generated, ignored, and not
    // yours to edit.
    assert.match(readme, /`src\/routes\.d\.ts` is rewritten/);
    assert.match(readme, /already listed in `.gitignore`/);
    assert.match(readme, /github\.com\/Rlzee\/next-vite-router/);
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
  }
});

test("the starter reads in a dark theme and loads no file from disk", () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "nvr-cli-starter-"));
  const project = makeViteProject(path.join(root, "project"));
  try {
    const { code, stdout } = runCli(["configure", "--yes", "--dir", project]);
    assert.equal(code, 0, `configure exited with ${code}:\n${stdout}`);

    const starter = [
      read(path.join(project, "src", "app", "layout.tsx")),
      read(path.join(project, "src", "app", "page.tsx")),
      read(path.join(project, "src", "app", "example", "page.tsx")),
    ].join("\n");

    // The mark is drawn inline. A scaffold deletes the template's `assets/`
    // folder, so an imported image would be an import of a file that is gone.
    assert.match(starter, /<svg/);
    assert.doesNotMatch(starter, /\.(svg|png|jpe?g|gif|webp)\b/);
    assert.doesNotMatch(starter, /assets\//);

    const css = read(path.join(project, "src", "globals.css"));
    assert.match(css, /color-scheme: light dark/);
    assert.match(css, /@media \(prefers-color-scheme: dark\)/);
    // The starter styles itself with plain classes from this file, so it reads the
    // same with and without Tailwind: only the import above it differs.
    assert.match(css, /--background: #ffffff/);
    assert.match(starter, /className="card"/);
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
  }
});

test("configure does not replace a README, a stylesheet, or a page that exists", () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "nvr-cli-keep-"));
  const project = makeViteProject(path.join(root, "project"));
  const readme = "# My project\n\nWritten by hand.\n";
  const css = "/* my own stylesheet */\nbody { color: teal; }\n";
  const home = "export default function Page() {\n  return <h1>mine</h1>;\n}\n";
  try {
    fs.writeFileSync(path.join(project, "README.md"), readme, "utf8");
    fs.writeFileSync(path.join(project, "src", "globals.css"), css, "utf8");
    fs.mkdirSync(path.join(project, "src", "app"), { recursive: true });
    fs.writeFileSync(path.join(project, "src", "app", "page.tsx"), home, "utf8");

    const { code, stdout } = runCli(["configure", "--yes", "--dir", project]);
    assert.equal(code, 0, `configure exited with ${code}:\n${stdout}`);

    assert.equal(read(path.join(project, "README.md")), readme);
    assert.equal(read(path.join(project, "src", "globals.css")), css);
    assert.equal(read(path.join(project, "src", "app", "page.tsx")), home);

    // Kept files are named, so a reader is never left guessing which documents
    // the run wrote and which it did not touch.
    assert.match(
      stdout,
      /left exactly as it was: src\/globals\.css, src\/app\/page\.tsx, README\.md\./,
    );

    // And the routes that were missing still arrive, so one existing page does not
    // cost the project its starter layout.
    assert.match(read(path.join(project, "src", "app", "layout.tsx")), /<Outlet \/>/);
    assert.match(read(path.join(project, "src", "app", "example", "page.tsx")), /ExamplePage/);
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
  }
});
